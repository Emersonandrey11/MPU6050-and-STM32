#!/usr/bin/env python3
"""Generate Src/font_data.c + Inc/font.h from X11 "misc-fixed" bitmap fonts.

The misc-fixed fonts are public domain and were designed for 1-bit screens,
so they stay sharp on the ST7789V without anti-aliasing.

Each glyph is stored as one uint16_t per pixel row, MSB = leftmost pixel.
Characters 32..126 are ASCII; two extra glyphs follow, so they get the next
codes:
    0x7F = degree sign (U+00B0)   -> use FONT_DEG  in C strings
    0x80 = plus-minus  (U+00B1)   -> use FONT_PM

Needs Pillow and the X11 misc fonts (Debian/Ubuntu: xfonts-base):
    python3 tools/gen_font.py
"""
import gzip
import os

from PIL import PcfFontFile

FONT_DIR = "/usr/share/fonts/X11/misc"
FONTS = [  # C name, X11 font, use
    ("font_small", "7x14B", "labels"),
    ("font_big", "9x18B", "values"),
]
CHARS = list(range(32, 127)) + [0xB0, 0xB1]   # ASCII + degree + plus-minus
assert CHARS.index(0xB0) + 32 == 0x7F and CHARS.index(0xB1) + 32 == 0x80

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def load(name):
    path = os.path.join(FONT_DIR, name + "-ISO8859-1.pcf.gz")
    with gzip.open(path) as fp:
        return PcfFontFile.PcfFontFile(fp)


def glyph_rows(font, code, w, h):
    g = font.glyph[code]
    if g is None:
        return [0] * h
    im = g[3].convert("L")
    rows = []
    for y in range(h):
        bits = 0
        for x in range(w):
            if im.getpixel((x, y)) > 127:
                bits |= 0x8000 >> x
        rows.append(bits)
    return rows


def main():
    c_out = [
        "/* Generated by tools/gen_font.py from the public-domain X11 misc-fixed fonts. Do not edit. */",
        '#include "font.h"',
        "",
    ]
    h_names = []
    for cname, xname, use in FONTS:
        f = load(xname)
        w, h = f.glyph[ord("A")][2][2:]
        assert w <= 16, "rows are stored as uint16_t"
        c_out.append("/* %s: %dx%d, %s */" % (xname, w, h, use))
        c_out.append("static const uint16_t %s_rows[%d * %d] = {" % (cname, len(CHARS), h))
        for code in CHARS:
            rows = glyph_rows(f, code, w, h)
            label = chr(code) if 32 < code < 127 and chr(code) not in "\\*/" else "0x%02X" % code
            c_out.append("    " + ", ".join("0x%04X" % r for r in rows) + ",  /* %s */" % label)
        c_out.append("};")
        c_out.append("const font_t %s = { %d, %d, 32, %d, %s_rows };" % (cname, w, h, len(CHARS), cname))
        c_out.append("")
        h_names.append((cname, xname, w, h, use))

    h_out = [
        "/**",
        " * @file  font.h",
        " * @brief Fixed-width bitmap fonts (generated by tools/gen_font.py).",
        " */",
        "#ifndef FONT_H",
        "#define FONT_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint8_t  width;        /* pixels, <= 16                         */",
        "    uint8_t  height;       /* pixels = rows per glyph              */",
        "    uint8_t  first;        /* code of the first glyph (32 = space) */",
        "    uint8_t  count;        /* number of glyphs                     */",
        "    const uint16_t *rows;  /* count * height rows, MSB = left pixel */",
        "} font_t;",
        "",
        "/* Extra glyphs after ASCII 126 (use as string pieces: \"20\" FONT_DEG \"C\") */",
        '#define FONT_DEG  "\\x7F"',
        '#define FONT_PM   "\\x80"',
        "",
    ]
    for cname, xname, w, h, use in h_names:
        h_out.append("extern const font_t %s;   /* %s, %dx%d, %s */" % (cname, xname, w, h, use))
    h_out += ["", "#endif /* FONT_H */", ""]

    with open(os.path.join(ROOT, "Src", "font_data.c"), "w") as fp:
        fp.write("\n".join(c_out))
    with open(os.path.join(ROOT, "Inc", "font.h"), "w") as fp:
        fp.write("\n".join(h_out))
    print("wrote Src/font_data.c and Inc/font.h")


if __name__ == "__main__":
    main()
